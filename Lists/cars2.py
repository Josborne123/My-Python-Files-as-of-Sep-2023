cars = ['bmw', 'audi', 'toyota', 'subaru']


print("Here is the original list:")
print(cars)

print("\nHere is the sorted list")
print(sorted(cars))

print("Here is the original list again:")
print(cars)

#Here it is reversing the order of the list, not reversing the alphabetical order of the list
cars.reverse()
print(cars)
